-- Tester feedback: the "Feedback" button on the dev site (components/
-- FeedbackWidget.tsx) saves comments here. Anyone on the dev site can send
-- one (signed in or not); only admins can read them. Reads go through
-- admin_feedback(), writes through submit_feedback().

create table if not exists public.tester_feedback (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_id     uuid references public.profiles (id) on delete set null,
  category    text not null check (category in ('bug', 'idea', 'question', 'other')),
  message     text not null check (char_length(message) between 1 and 2000),
  page_path   text check (char_length(page_path) <= 300),
  viewport    text check (char_length(viewport) <= 40),
  user_agent  text check (char_length(user_agent) <= 300),
  environment text check (char_length(environment) <= 40),
  status      text not null default 'new' check (status in ('new', 'done')),
  admin_note  text check (char_length(admin_note) <= 1000)
);

create index if not exists tester_feedback_created on public.tester_feedback (created_at desc);
create index if not exists tester_feedback_user on public.tester_feedback (user_id);

alter table public.tester_feedback enable row level security;
revoke all on public.tester_feedback from anon, authenticated;

-- Send feedback. Signed-in testers are linked to their account. Limited to
-- 30 a hour per account, and 60 a hour for everyone signed out.
create or replace function public.submit_feedback(
  p_category text,
  p_message text,
  p_page_path text default null,
  p_viewport text default null,
  p_user_agent text default null,
  p_environment text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  body text := btrim(coalesce(p_message, ''));
  new_id bigint;
  hourly_limit integer := case when auth.uid() is null then 60 else 30 end;
begin
  if p_category not in ('bug', 'idea', 'question', 'other') then
    raise exception 'Choose a type of feedback' using errcode = 'P0001';
  end if;
  if body = '' then
    raise exception 'Write a little about it' using errcode = 'P0001';
  end if;
  if char_length(body) > 2000 then
    raise exception 'Keep it under 2,000 characters' using errcode = 'P0001';
  end if;
  if (select count(*) from public.tester_feedback
       where created_at > now() - interval '1 hour'
         and (user_id = uid or (uid is null and user_id is null))) >= hourly_limit then
    raise exception 'That''s a lot of feedback at once. Thank you! Please wait a little and try again' using errcode = 'P0001';
  end if;

  insert into public.tester_feedback (user_id, category, message, page_path, viewport, user_agent, environment)
  values (uid, p_category, body, left(p_page_path, 300), left(p_viewport, 40), left(p_user_agent, 300), left(p_environment, 40))
  returning id into new_id;
  return new_id;
end;
$$;

revoke execute on function public.submit_feedback(text, text, text, text, text, text) from public;
grant execute on function public.submit_feedback(text, text, text, text, text, text) to anon, authenticated, service_role;

-- Admin: all feedback, newest first.
create or replace function public.admin_feedback()
returns table (
  id bigint,
  created_at timestamptz,
  username text,
  category text,
  message text,
  page_path text,
  viewport text,
  user_agent text,
  environment text,
  status text,
  admin_note text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Admins only' using errcode = '42501';
  end if;
  return query
    select f.id, f.created_at, p.username, f.category, f.message, f.page_path, f.viewport, f.user_agent,
           f.environment, f.status, f.admin_note
      from public.tester_feedback f
      left join public.profiles p on p.id = f.user_id
     order by (f.status = 'done'), f.created_at desc
     limit 500;
end;
$$;

revoke execute on function public.admin_feedback() from public, anon;
grant execute on function public.admin_feedback() to authenticated, service_role;

-- Admin: mark feedback done (or new again), with an optional note.
create or replace function public.admin_set_feedback_status(p_id bigint, p_status text, p_note text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Admins only' using errcode = '42501';
  end if;
  if p_status not in ('new', 'done') then
    raise exception 'Unknown status' using errcode = 'P0001';
  end if;
  update public.tester_feedback
     set status = p_status,
         admin_note = coalesce(nullif(btrim(p_note), ''), admin_note)
   where id = p_id;
end;
$$;

revoke execute on function public.admin_set_feedback_status(bigint, text, text) from public, anon;
grant execute on function public.admin_set_feedback_status(bigint, text, text) to authenticated, service_role;
